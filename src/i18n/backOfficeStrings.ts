const INVENTORY_MOVEMENT_KEYS: Record<string, BackOfficeStringKey> = {
  receive: "movementReceive",
  manual_adjust: "movementManualAdjust",
  stock_take: "movementStockTake",
  sale: "movementSale",
  refund: "movementRefund",
};

function ownedLabel(
  language: Language,
  value: string,
  keys: Record<string, BackOfficeStringKey>,
): string {
  const key = keys[value.trim().toLowerCase()];
  return key ? backOfficeText(language, key) : value;
}

export const reportSaleStatusText = (language: Language, value: string): string =>
  ownedLabel(language, value, SALE_STATUS_KEYS);

export function reportPaymentMethodsText(language: Language, value: string): string {
  const separator = language === "ar" ? "، " : ", ";
  return value
    .split(",")
    .map((method) => ownedLabel(language, method.trim(), PAYMENT_METHOD_KEYS))
    .join(separator);
}

export const cashEventTypeText = (language: Language, value: string): string =>
  ownedLabel(language, value, CASH_EVENT_KEYS);

export const inventoryMovementTypeText = (language: Language, value: string): string =>
  ownedLabel(language, value, INVENTORY_MOVEMENT_KEYS);
